#!/usr/bin/env python3
"""Generate symbolic-C copies of a transpiled QE crate's B functions.

    python3 scripts/gen_b_lin.py QE_LIB_RS OUT_RS

Each `compute_b_t_T_l_N(.., C: RealNumRep, ..) -> IntervalList<RealNumRep>`
becomes `compute_b_lin_t_T_l_N(.., C: Lin, ..) -> Option<IntervalList<Lin>>`
(see `ds::lin`).  The body is unchanged except that

* every `Bound::Included(e)` / `Bound::Excluded(e)` becomes a `Lin` bound,
* every input but C, and every constant, is lifted to a constant `Lin`,
* an `assert!` is a clause of the B formula that does not mention B (it
  constrains C, or only the observations), so it returns `None` (no B for
  this C) instead of panicking.  Only the loss-count check stays an
  assertion.

The output is a module for `network_model_nc`; regenerate it whenever the QE
crate is regenerated.
"""

import re
import sys


def matching_paren(text, open_idx):
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced parentheses")


def functions(src):
    """(name, text) of every top-level `pub fn compute_b_t_*`."""
    for m in re.finditer(r"^pub fn (compute_b_t_\d+_l_\d+)\(", src, re.M):
        end = src.index("\n}\n", m.start()) + 3
        yield m.group(1), src[m.start():end]


def wrap_bounds(body):
    out, i = [], 0
    pat = re.compile(r"Bound::(Included|Excluded)\(")
    while True:
        m = pat.search(body, i)
        if not m:
            out.append(body[i:])
            return "".join(out)
        close = matching_paren(body, m.end() - 1)
        inner = wrap_bounds(body[m.end():close])
        out.append(body[i:m.start()])
        out.append(f"Bound::{m.group(1)}(Lin::from({inner}))")
        i = close + 1


def convert_asserts(body):
    out, i = [], 0
    while True:
        j = body.find("assert!(", i)
        if j < 0:
            out.append(body[i:])
            return "".join(out)
        close = matching_paren(body, j + len("assert!"))
        cond = body[j + len("assert!("):close]
        assert body[close + 1] == ";"
        out.append(body[i:j])
        if not re.fullmatch(r"\s*l\.len\(\) == \d+\s*", cond):
            out.append(f"if !({cond}) {{\n        return None;\n    }}")
        else:
            out.append(body[j:close + 2])
        i = close + 2


def convert(name, text):
    text = text.replace(f"pub fn {name}(", f"pub fn {name.replace('compute_b_', 'compute_b_lin_')}(", 1)
    assert "    C: RealNumRep,\n" in text, name
    text = text.replace("    C: RealNumRep,\n", "    C: Lin,\n", 1)
    text = text.replace(") -> IntervalList<RealNumRep> {", ") -> Option<IntervalList<Lin>> {", 1)
    text = text.replace(
        "let mut ret = IntervalList::new_interval(",
        "let mut ret: IntervalList<Lin> = IntervalList::new_interval(",
        1,
    )
    assert text.endswith("\n    ret\n}\n"), name
    text = text[: -len("\n    ret\n}\n")] + "\n    Some(ret)\n}\n"
    # Lift every input and constant to `Lin`, so that all arithmetic and
    # comparisons are between `Lin` values.
    head, body = text.split(" {\n", 1)
    params = re.findall(r"^    (\w+): (?:&\[RealNumRep\]|RealNumRep),$", head, re.M)
    lifts = []
    for p in params:
        if p in ("a", "l", "s"):
            lifts.append(f"    let {p}: Vec<Lin> = {p}.iter().map(|&x| Lin::from(x)).collect();")
        else:
            lifts.append(f"    let {p} = Lin::from({p});")
    body = body.replace("RealNumRep::new(", "lc(")
    text = head + " {\n" + "\n".join(lifts) + "\n" + body
    return convert_asserts(wrap_bounds(text))


def main():
    src = open(sys.argv[1]).read()
    fns = list(functions(src))
    assert fns, "no B functions found"
    plain = "K: RealNumRep" not in fns[0][1]
    args = "&[RealNumRep], &[RealNumRep], &[RealNumRep], RealNumRep, Lin"
    if not plain:
        args += ", RealNumRep, RealNumRep"
    out = [
        f"// Generated by scripts/gen_b_lin.py from {sys.argv[1].split('synthesizer/')[-1]}.",
        "// Do not edit by hand.",
        "#![allow(clippy::all, non_snake_case, unused_parens, unused_mut, unused_variables)]",
        "use ds::interval::{Interval, IntervalList};",
        "use ds::lin::Lin;",
        "use ds::*;",
        "use lazy_static::lazy_static;",
        "use std::collections::HashMap;",
        "use std::ops::Bound;",
        "",
        "fn lc(n: i32, d: i32) -> Lin {",
        "    Lin::from(RealNumRep::new(n, d))",
        "}",
        "",
        f"pub type QeFunBLin = fn({args}) -> Option<IntervalList<Lin>>;",
        "",
    ]
    table = []
    for name, text in fns:
        out.append(convert(name, text))
        t, n = re.match(r"compute_b_t_(\d+)_l_(\d+)", name).groups()
        table.append(f"        (({t}, {n}), {name.replace('compute_b_', 'compute_b_lin_')} as QeFunBLin),")
    out += [
        "lazy_static! {",
        "    pub static ref COMPUTE_B_LIN: HashMap<(i32, i32), QeFunBLin> = HashMap::from([",
        *table,
        "    ]);",
        "}",
        "",
    ]
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
